using System;
using System.Collections.Generic;
using Eternals.LevelManagement.Addressables;
using UnityEngine;
using UnityEngine.AddressableAssets;
using UnityEngine.ResourceManagement.AsyncOperations;

namespace Eternals.LevelManagement
{
    /// <summary>
    /// Game-agnostic level lifecycle contract. Concrete games own their board,
    /// progress, UI, rewards, analytics, and level-data types.
    /// </summary>
    public abstract class LevelManagerBase : MonoBehaviour
    {
        public abstract int CurrentLevelIndex { get; }
        public abstract int LevelCount { get; }
        public abstract bool IsLoadingLevel { get; }

        public abstract bool LoadLevel(int levelIndex);
        public abstract void RestartLevel();

        public virtual bool LoadNextLevel()
        {
            int levelCount = LevelCount;
            if (levelCount <= 0)
                return false;

            int nextLevelIndex = CurrentLevelIndex < 0
                ? 0
                : (CurrentLevelIndex + 1) % levelCount;
            return LoadLevel(nextLevelIndex);
        }

        public void WinGame()
        {
            if (CanWinGame())
                OnWinGame();
        }

        public void LoseGame()
        {
            if (CanLoseGame())
                OnLoseGame();
        }

        protected virtual bool CanWinGame()
        {
            return true;
        }

        protected virtual bool CanLoseGame()
        {
            return true;
        }

        protected abstract void OnWinGame();
        protected abstract void OnLoseGame();
    }

    public abstract class LevelDataManagerSettingsBase : ScriptableObject
    {
        [Header("Addressables")]
        [Tooltip("Load remote Addressable levels first. Local levels remain available as an offline fallback.")]
        [SerializeField] private bool useAddressables;

        [Tooltip("Discover the current remote level list from the Addressables label at runtime.")]
        [SerializeField] private bool discoverAddressablesAtRuntime = true;

        [Tooltip("Addressables label used to discover remote level assets.")]
        [SerializeField] private string addressableLabel = "GameLevels";

        [Tooltip("Ordered remote level references generated by the Editor sync utility.")]
        [SerializeField, HideInInspector] private List<AssetReference> addressableLevels = new();

        public bool UseAddressables => useAddressables;
        public bool DiscoverAddressablesAtRuntime => discoverAddressablesAtRuntime;
        public string AddressableLabel => addressableLabel;
        public IReadOnlyList<AssetReference> AddressableLevels => addressableLevels;

        protected int SerializedAddressableLevelCount =>
            addressableLevels != null ? addressableLevels.Count : 0;

        protected AssetReference GetAddressableLevelReference(int index)
        {
            return addressableLevels != null && index >= 0 && index < addressableLevels.Count
                ? addressableLevels[index]
                : null;
        }

        public void SetAddressableLevelGuids(IReadOnlyList<string> assetGuids)
        {
            int count = assetGuids != null ? assetGuids.Count : 0;
            addressableLevels = new List<AssetReference>(count);
            for (int i = 0; i < count; i++)
                addressableLevels.Add(new AssetReference(assetGuids[i]));
        }
    }

    /// <summary>
    /// Game-agnostic local/remote level catalog. Concrete games only provide
    /// their local level list and level-data type.
    /// </summary>
    public abstract class LevelDataManagerBase<TLevel> : LevelDataManagerSettingsBase
        where TLevel : UnityEngine.Object
    {
        private AddressableLevelCatalog<TLevel> runtimeAddressableCatalog;

        public virtual int Count => !UseAddressables
            ? LocalLevelCount
            : runtimeAddressableCatalog != null && runtimeAddressableCatalog.Succeeded
                ? runtimeAddressableCatalog.Count
                : LocalLevelCount > 0
                    ? LocalLevelCount
                    : SerializedAddressableLevelCount;

        public virtual bool AddressableLevelsReady =>
            !UseAddressables ||
            !DiscoverAddressablesAtRuntime ||
            (runtimeAddressableCatalog != null && runtimeAddressableCatalog.IsReady);

        public abstract int LocalLevelCount { get; }

        public virtual bool InitializeAddressableLevels(Action<bool> completed = null)
        {
            if (!UseAddressables)
            {
                completed?.Invoke(true);
                return true;
            }

            if (!DiscoverAddressablesAtRuntime)
            {
                bool hasRemoteReferences = SerializedAddressableLevelCount > 0;
                completed?.Invoke(hasRemoteReferences);
                return hasRemoteReferences;
            }

            if (runtimeAddressableCatalog == null ||
                !string.Equals(
                    runtimeAddressableCatalog.Label,
                    AddressableLabel,
                    StringComparison.Ordinal))
            {
                runtimeAddressableCatalog?.Dispose();
                runtimeAddressableCatalog = new AddressableLevelCatalog<TLevel>(AddressableLabel);
            }

            return runtimeAddressableCatalog.Initialize(succeeded =>
            {
                if (!succeeded)
                {
                    Debug.LogError(
                        $"{GetType().Name} could not discover Addressable levels with label " +
                        $"'{AddressableLabel}': {runtimeAddressableCatalog.LastError} " +
                        "Local levels will be used when available.",
                        this);
                }

                completed?.Invoke(succeeded);
            });
        }

        public virtual bool TryLoadAddressableLevelAsync(
            int index,
            out AsyncOperationHandle<TLevel> handle)
        {
            if (runtimeAddressableCatalog != null &&
                runtimeAddressableCatalog.TryLoadLevelAsync(index, out handle))
            {
                return true;
            }

            AssetReference reference = GetAddressableLevelReference(index);
            if (reference != null && reference.RuntimeKeyIsValid())
            {
                handle = UnityEngine.AddressableAssets.Addressables.LoadAssetAsync<TLevel>(
                    reference.RuntimeKey);
                return true;
            }

            handle = default;
            return false;
        }

        public abstract TLevel GetLevelData(int index);

        public virtual TLevel GetLocalFallbackLevelData(int requestedIndex, out int localIndex)
        {
            localIndex = -1;
            int localCount = LocalLevelCount;
            if (localCount <= 0 || requestedIndex < 0)
                return null;

            int firstCandidate = requestedIndex % localCount;
            for (int offset = 0; offset < localCount; offset++)
            {
                int candidateIndex = (firstCandidate + offset) % localCount;
                TLevel level = GetLevelData(candidateIndex);
                if (level == null)
                    continue;

                localIndex = candidateIndex;
                return level;
            }

            return null;
        }

        public virtual int GetMaxLevelIndex()
        {
            return Count > 0 ? Count : -1;
        }

        protected virtual void OnDisable()
        {
            runtimeAddressableCatalog?.Dispose();
            runtimeAddressableCatalog = null;
        }
    }
}
